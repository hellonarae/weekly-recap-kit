import type { Script, ThemeConfig } from '../../src/content/types';

// Colour helpers: derive the whole palette from two hex colours so a kit teacher changes one line.
type HSL = { h: number; s: number; l: number };

function hexToHsl(hex: string): HSL {
  const n = parseInt(hex.slice(1), 16);
  const r = ((n >> 16) & 255) / 255, g = ((n >> 8) & 255) / 255, b = (n & 255) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return { h: 0, s: 0, l };
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h = 0;
  if (max === r) h = ((g - b) / d + (g < b ? 6 : 0)) * 60;
  else if (max === g) h = ((b - r) / d + 2) * 60;
  else h = ((r - g) / d + 4) * 60;
  return { h, s, l };
}

function hsl({ h, s, l }: HSL): string {
  const c = (1 - Math.abs(2 * l - 1)) * s;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l - c / 2;
  const [r1, g1, b1] =
    h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  const to = (v: number) => Math.round((v + m) * 255).toString(16).padStart(2, '0');
  return `#${to(r1!)}${to(g1!)}${to(b1!)}`.toUpperCase();
}

function luminance(hex: string): number {
  const n = parseInt(hex.slice(1), 16);
  const ch = (v: number) => { const c = v / 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
  return 0.2126 * ch((n >> 16) & 255) + 0.7152 * ch((n >> 8) & 255) + 0.0722 * ch(n & 255);
}

export function deriveTokens(theme: ThemeConfig): Record<string, string> {
  const p = hexToHsl(theme.primary);
  const a = hexToHsl(theme.accent);
  const t: Record<string, string> = {
    paper: hsl({ h: p.h, s: 0.4, l: 0.98 }),
    surface: '#FFFFFF',
    'surface-2': hsl({ h: p.h, s: 0.35, l: 0.95 }),
    line: hsl({ h: p.h, s: 0.3, l: 0.9 }),
    ink: hsl({ h: p.h, s: 0.33, l: 0.15 }),
    'ink-2': hsl({ h: p.h, s: 0.17, l: 0.37 }),
    'ink-3': hsl({ h: p.h, s: 0.13, l: 0.44 }), // ≥ 4.5:1 on white for 13 px text
    primary: theme.primary.toUpperCase(),
    'primary-deep': hsl({ h: p.h, s: p.s, l: p.l * 0.73 }),
    'primary-soft': hsl({ h: p.h, s: 0.5, l: 0.92 }),
    'on-primary': luminance(theme.primary) > 0.4 ? hsl({ h: p.h, s: 0.33, l: 0.15 }) : '#FFFFFF',
    accent: theme.accent.toUpperCase(),
    'accent-ink': hsl({ h: a.h, s: 1, l: 0.24 }),
    'accent-soft': hsl({ h: a.h, s: 1, l: 0.88 }),
    correct: '#2E8B57',
    wrong: '#C8323C',
  };
  // Six speaker colours by rotating the primary hue; kept mid-light so white initials read.
  for (let i = 0; i < 6; i++) t[`speaker-${i + 1}`] = hsl({ h: (p.h + i * 55) % 360, s: 0.55, l: 0.42 });
  return { ...t, ...(theme.tokens ?? {}) };
}

const SCRIPT_FONTS: Record<Script, string> = {
  hangul: '',
  latin: '',
  hanzi: '"Noto Sans SC", ',
  kana: '"Noto Sans JP", ',
  cyrillic: '',
};

export function writeTokens(theme: ThemeConfig, script: Script): string {
  const t = deriveTokens(theme);
  const vars = Object.entries(t).map(([k, v]) => `  --${k}: ${v};`).join('\n');
  return `/* Generated by scripts/build-content.ts from course.yml → app.theme. Do not edit. */
:root {
${vars}
  --font-ui: "Pretendard Variable", Pretendard, system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
  --font-tl: ${SCRIPT_FONTS[script]}"Pretendard Variable", Pretendard, system-ui, sans-serif;
  --radius-s: 14px;
  --radius-m: 20px;
  --radius-l: 28px;
  --shadow-float: 0 8px 24px rgba(0, 0, 0, 0.12);
}
`;
}
