import fs from 'node:fs';
import path from 'node:path';
import type { ContentBundle, Issue } from '../../src/content/types';
import type { BuildArgs } from './args';
import { appIconPng } from './png';

/** Copies referenced flags, teacher images and generated audio into public/. Returns issues. */
export function copyAssets(bundle: ContentBundle, args: BuildArgs): Issue[] {
  const issues: Issue[] = [];
  const pub = path.join(args.root, 'public');
  for (const sub of ['_img', '_audio']) fs.rmSync(path.join(pub, sub), { recursive: true, force: true });
  const flagsDir = path.join(args.root, 'node_modules/flag-icons/flags/4x3');

  for (const level of bundle.levels) {
    const levelDir = path.join(args.levelsDir, path.basename(path.dirname(bundle.course.levels.find((l) => l.id === level.id)?.vocab ?? `levels/${level.id}/x`)));
    const entries = [...level.units.flatMap((u) => u.entries), ...level.weeks.flatMap((w) => w.vocab)];
    for (const e of entries) {
      if (!e.img) continue;
      if (e.img.startsWith('flag:')) {
        const cc = e.img.slice(5);
        const src = path.join(flagsDir, `${cc}.svg`);
        if (!fs.existsSync(src)) { issues.push({ level: 'error', file: `${level.id} vocab`, message: `"${e.tl}": no flag "${cc}" in flag-icons (use an ISO 3166 code like gb, kr, gb-eng)` }); continue; }
        const dst = path.join(pub, '_img/flags', `${cc}.svg`);
        fs.mkdirSync(path.dirname(dst), { recursive: true });
        fs.copyFileSync(src, dst);
      } else if (e.img.startsWith('file:')) {
        const name = e.img.slice(5);
        const src = path.join(levelDir, 'images', name);
        if (!fs.existsSync(src)) { issues.push({ level: 'error', file: `${level.id} vocab`, message: `"${e.tl}": img file "${name}" not found in ${path.relative(args.root, levelDir)}/images/` }); continue; }
        const dst = path.join(pub, '_img', level.id, name);
        fs.mkdirSync(path.dirname(dst), { recursive: true });
        fs.copyFileSync(src, dst);
      }
    }
    // Build-time audio (Phase D): levels/<L>/weeks/week-NN/audio/{index.json,*.mp3} and levels/<L>/audio for vocab
    const audioDirs = [
      ...level.weeks.map((w) => [path.join(args.root, w.dir, 'audio'), path.join(pub, '_audio', level.id, `week-${String(w.week).padStart(2, '0')}`)] as const),
      [path.join(levelDir, 'audio'), path.join(pub, '_audio', level.id, 'vocab')] as const,
    ];
    for (const [src, dst] of audioDirs) {
      if (!fs.existsSync(src)) continue;
      fs.mkdirSync(dst, { recursive: true });
      for (const f of fs.readdirSync(src)) if (/\.(mp3|json)$/.test(f)) fs.copyFileSync(path.join(src, f), path.join(dst, f));
    }
  }
  return issues;
}

/** Writes src/generated/icons.ts with only the lucide icons the content uses (tree-shaken, no 1k-chunk dynamic map). */
export function writeIconsModule(bundle: ContentBundle, args: BuildArgs, outDir: string): Issue[] {
  const issues: Issue[] = [];
  const names = new Set<string>();
  for (const level of bundle.levels) for (const e of [...level.units.flatMap((u) => u.entries), ...level.weeks.flatMap((w) => w.vocab)]) {
    if (e.img?.startsWith('icon:')) names.add(e.img.slice(5));
  }
  const valid = [...names].filter((n) => {
    const ok = fs.existsSync(path.join(args.root, 'node_modules/lucide-react/dist/esm/icons', `${n}.js`));
    if (!ok) issues.push({ level: 'error', file: 'vocab', message: `img icon:${n} is not a lucide icon name (see https://lucide.dev/icons)` });
    return ok;
  }).sort();
  const pascal = (n: string) => n.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
  const src = `// Generated by scripts/build-content.ts — lucide icons referenced by img: icon:<name>. Do not edit.
import type { LucideIcon } from 'lucide-react';
${valid.length ? `import { ${valid.map((n) => `${pascal(n)} as I_${pascal(n)}`).join(', ')} } from 'lucide-react';` : ''}
export const icons: Record<string, LucideIcon> = {
${valid.map((n) => `  '${n}': I_${pascal(n)},`).join('\n')}
};
`;
  fs.writeFileSync(path.join(outDir, 'icons.ts'), src);
  return issues;
}

/** App icons + web manifest so the site can be added to a phone home screen (standalone, with the brand mark). */
export function writePwaFiles(bundle: ContentBundle, args: BuildArgs): void {
  const pub = path.join(args.root, 'public');
  const { primary, accent } = bundle.course.app.theme;
  fs.mkdirSync(path.join(pub, '_img'), { recursive: true });
  for (const size of [180, 192, 512]) fs.writeFileSync(path.join(pub, '_img', `app-icon-${size}.png`), appIconPng(size, primary, accent));
  const manifest = {
    name: bundle.course.app.name,
    short_name: bundle.course.app.short_name,
    start_url: './',   // relative: works at / (Vercel) and at /<repo>/ (GitHub Pages)
    display: 'standalone',
    background_color: '#FBF9FD',
    theme_color: primary,
    icons: [192, 512].map((s) => ({ src: `_img/app-icon-${s}.png`, sizes: `${s}x${s}`, type: 'image/png' })),
  };
  fs.writeFileSync(path.join(pub, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));
}
